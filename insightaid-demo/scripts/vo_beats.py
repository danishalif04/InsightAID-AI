"""Find where each sentence starts in every competition voice clip.

    python scripts/vo_beats.py

For each clip, the sentence boundaries are matched to REAL pauses in the
audio: every silent gap (>= 120 ms below the clip's noise floor + 12 dB) is a
candidate, and each boundary takes the candidate nearest to its
word-proportional estimate. Writes src/competition/voBeats.ts with the start
frame (30 fps, relative to the clip) of every sentence, so the picture can
change exactly when the narration does.
"""
import json
import re

import numpy as np
from scipy.io import wavfile

FPS = 30
# Caption text per clip, exactly as in Competition.tsx COMP_LINES.
src = open('src/competition/Competition.tsx', encoding='utf8').read()
lines = {int(m.group(1)): m.group(2) for m in re.finditer(r"\{ scene: (\d+), from: \d+, to: \d+, text: ['\"](.+?)['\"] \}", src)}

out = {}
for scene, text in sorted(lines.items()):
    sents = [s for s in re.split(r'(?<=[.?!])\s+', text) if s]
    fs, x = wavfile.read(f'public/assets/vo-comp/s{scene:02d}.wav')
    x = x.astype(float) / 32768
    hop = int(0.01 * fs)
    rms = np.sqrt(np.array([np.mean(x[i:i + hop] ** 2) for i in range(0, len(x) - hop, hop)]) + 1e-12)
    db = 20 * np.log10(rms)
    floor = np.percentile(db, 8)
    silent = db < floor + 12
    gaps = []  # (start_s, end_s)
    i = 0
    while i < len(silent):
        if silent[i]:
            j = i
            while j < len(silent) and silent[j]:
                j += 1
            if (j - i) * 0.01 >= 0.12:
                gaps.append((i * 0.01, j * 0.01))
            i = j
        else:
            i += 1
    # speech start/end
    voiced = np.where(~silent)[0]
    t0, t1 = voiced[0] * 0.01, voiced[-1] * 0.01
    words = [len(s.split()) for s in sents]
    total = sum(words)
    starts = [t0]
    acc = 0
    used = set()
    for k in range(1, len(sents)):
        acc += words[k - 1]
        est = t0 + (t1 - t0) * acc / total
        cands = [(abs((g[1]) - est), gi) for gi, g in enumerate(gaps) if gi not in used and g[0] > starts[-1] + 0.3]
        if cands and min(cands)[0] < 1.6:
            gi = min(cands)[1]
            used.add(gi)
            starts.append(gaps[gi][1])  # speech resumes at the end of the gap
        else:
            starts.append(est)
    out[scene] = [round(s * FPS) for s in starts]
    print(scene, [f'{s:.2f}s' for s in starts])

with open('src/competition/voBeats.ts', 'w', encoding='utf8') as fh:
    fh.write('// Generated by scripts/vo_beats.py: start frame of each sentence in each\n')
    fh.write('// voice clip (relative to the clip start), matched to real pauses in the audio.\n')
    fh.write('export const VO_BEATS: Record<number, number[]> = ' + json.dumps(out) + '\n')
print('wrote src/competition/voBeats.ts')
